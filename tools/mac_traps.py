#!/usr/bin/env python3
"""Riptide on the classic Mac OS: turn the list of Toolbox calls (src/mac/app/traps.txt) into
C-callable glue for the m68k ELF GCC.

    mac_traps.py traps.txt -s toolbox_glue.S -H toolbox_gen.h

Each C function takes its arguments the GCC way (each in a 4-byte stack slot, the value in its
low end) and makes the Pascal call: room for the result, the arguments pushed left to right (an
INTEGER or CHAR as a word, a BOOLEAN as a byte in the high half of a word), the trap word; the
trap pops the arguments and leaves the result. The glue keeps D2 (GCC expects it kept, Pascal
code may change it) and returns the result in D0 and, for a long or pointer, in A0 too: GCC's
m68k SVR4 ABI reads a pointer result from A0. A BOOLEAN comes back as 0 or 1, an INTEGER
sign-extended.
SPDX-License-Identifier: GPL-2.0-only
"""
import argparse, re

ap = argparse.ArgumentParser()
ap.add_argument('spec'); ap.add_argument('-s', required=True); ap.add_argument('-H', required=True)
a = ap.parse_args()
asm = ['| generated by tools/mac_traps.py from src/mac/app/traps.txt: do not edit', '\t.text']
hdr = ['/* generated by tools/mac_traps.py from src/mac/app/traps.txt: do not edit */',
       '#ifndef RT_MAC_TOOLBOX_GEN_H', '#define RT_MAC_TOOLBOX_GEN_H']
ctype = {'-': 'void', 'l': 'long', 'p': 'void *', 'w': 'short', 'b': 'int', 'c': 'int'}
for ln in open(a.spec):
    ln = ln.strip()
    if not ln or ln.startswith('#'):
        continue
    m = re.match(r'([0-9A-Fa-f]{4})\s+([-lpwb])\s+(\w+)\((.*)\)$', ln)
    if not m:
        raise SystemExit(f"bad line: {ln}")
    trap, res, name, args = m.groups()
    params = []
    if args.strip():
        for p in args.split(','):
            decl, kind = p.rsplit(':', 1)
            params.append((decl.strip(), kind.strip()))
    hdr.append(f"{ctype[res]} {name}({', '.join(d for d, _ in params) or 'void'});")
    asm += [f'\t.globl\t{name}', f'{name}:', '\tlink\t%a6,#0', '\tmove.l\t%d2,-(%sp)']
    if res in 'lp':
        asm.append('\tclr.l\t-(%sp)')
    elif res in 'wb':
        asm.append('\tclr.w\t-(%sp)')
    for i, (_, k) in enumerate(params):
        off = 8 + 4 * i
        if k == 'l':
            asm.append(f'\tmove.l\t{off}(%a6),-(%sp)')
        elif k in 'wc':
            asm.append(f'\tmove.w\t{off + 2}(%a6),-(%sp)')
        elif k == 'b':
            asm.append(f'\tmove.b\t{off + 3}(%a6),-(%sp)')
        else:
            raise SystemExit(f"{name}: kind {k}")
    asm.append(f'\t.short\t0x{trap.upper()}')
    if res in 'lp':
        asm += ['\tmove.l\t(%sp)+,%d0', '\tmove.l\t%d0,%a0']
    elif res == 'w':
        asm += ['\tmove.w\t(%sp)+,%d0', '\text.l\t%d0']
    elif res == 'b':
        asm += ['\tmoveq\t#0,%d0', '\ttst.b\t(%sp)+', '\tsne\t%d0', '\tneg.b\t%d0']
    asm += ['\tmove.l\t-4(%a6),%d2', '\tunlk\t%a6', '\trts']
hdr.append('#endif')
asm.append('\t.section .note.GNU-stack,"",@progbits')
open(a.s, 'w').write('\n'.join(asm) + '\n')
open(a.H, 'w').write('\n'.join(hdr) + '\n')
