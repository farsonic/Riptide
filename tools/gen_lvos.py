#!/usr/bin/env python3
# Riptide - generate AmigaOS library glue from LVO tables.
# SPDX-License-Identifier: GPL-2.0-only
#
# Table format (src/amiga/os/os_lvos.txt, src/amiga/lib_lvos.txt,
# src/amiga/mni_lvos.txt):
#
#   @lib NAME BASEVAR [prefix=PFX] [basetype=STRUCTNAME] [callprefix=PFX]
#   BIAS RETTYPE FUNC(TYPE ARG REG, ...) [= CNAME]
#
# BIAS is the positive library vector offset (LVO = -BIAS). REG is one of
# d0-d7/a0-a5. '#' starts a comment. BASEVAR '-' means the callers pass the
# library base explicitly as the first argument (drivers with many bases).
#
# Usage:
#   gen_lvos.py call CC TABLE LIB OUT.h
#       Inline functions calling LIB through its jump table. CC=gcc emits
#       GCC register-variable inline asm, CC=vbcc emits vbcc __reg() asm
#       inlines.
#   gen_lvos.py impl CC TABLE LIB OUT.(S|c) OUT.h
#       For a library Riptide implements: prototypes of the C functions
#       ("RET PFXFUNC(RTREG(a6) struct Library *base, RTREG(d0) T a, ...)",
#       always returning an integer type so the result is in d0) and the
#       MakeLibrary() vector table LIB_vectors[] (-1 terminated, from bias
#       6). CC=gcc: assembler file with register->stack trampolines; CC=vbcc:
#       C file whose vectors point straight at the __reg() functions.
#       Holes and "= null" entries return 0.
#   gen_lvos.py list TABLE LIB
#       Print "bias name regs".
import re
import sys

REGS = ['d%d' % i for i in range(8)] + ['a%d' % i for i in range(6)]
SCRATCH = ('d0', 'd1', 'a0', 'a1')


class Func:
    def __init__(self, bias, ret, name, args, cname):
        self.bias, self.ret, self.name, self.args, self.cname = bias, ret, name, args, cname


class Lib:
    def __init__(self, name, basevar, opts):
        self.name, self.basevar, self.opts = name, basevar, opts
        self.funcs = []


def parse(path):
    libs = {}
    cur = None
    line_re = re.compile(r'^(\d+)\s+(.+?)\s*\b([A-Za-z_]\w*)\s*\((.*)\)\s*(?:=\s*(\w+))?\s*$')
    for ln, raw in enumerate(open(path), 1):
        line = raw.split('#', 1)[0].strip()
        if not line:
            continue
        if line.startswith('@lib'):
            w = line.split()
            opts = dict(x.split('=', 1) for x in w[3:])
            cur = Lib(w[1], w[2], opts)
            libs[cur.name] = cur
            continue
        m = line_re.match(line)
        if not m or cur is None:
            sys.exit('%s:%d: syntax error' % (path, ln))
        bias, ret, name, argstr, cname = m.groups()
        args = []
        if argstr.strip():
            for a in argstr.split(','):
                t = a.split()
                if len(t) < 3 or t[-1] not in REGS:
                    sys.exit('%s:%d: bad argument "%s"' % (path, ln, a))
                args.append((' '.join(t[:-2]), t[-2], t[-1]))
        regs = [a[2] for a in args]
        if len(set(regs)) != len(regs):
            sys.exit('%s:%d: register used twice' % (path, ln))
        bias = int(bias)
        if bias % 6:
            sys.exit('%s:%d: bias not a multiple of 6' % (path, ln))
        if any(f.bias == bias for f in cur.funcs):
            sys.exit('%s:%d: duplicate bias %d' % (path, ln, bias))
        cur.funcs.append(Func(bias, ret.strip(), name, args, cname))
    for lib in libs.values():
        lib.funcs.sort(key=lambda f: f.bias)
    return libs


def is_void(t):
    return t in ('void', 'VOID')


def base_decl(lib):
    bt = lib.opts.get('basetype')
    return 'struct %s *' % bt if bt else 'struct Library *'


def gen_call(lib, cc, out):
    o = ['/* Generated by tools/gen_lvos.py from the LVO table - do not edit. */',
         '#ifndef _RT_GEN_%s_CALLS_H' % lib.name.upper(),
         '#define _RT_GEN_%s_CALLS_H' % lib.name.upper()]
    explicit = lib.basevar == '-'
    if not explicit:
        o.append('extern %s%s;' % (base_decl(lib), lib.basevar))
    pfx = lib.opts.get('callprefix', '')
    for f in lib.funcs:
        if f.bias <= 24:
            continue
        name = pfx + f.name
        names = [n for t, n, r in f.args]
        o.append('#define LVO_%s_%s (-%d)' % (lib.name, f.name, f.bias))
        if cc == 'vbcc':
            params = ['__reg("a6") void *'] + ['__reg("%s") %s' % (r, t) for t, n, r in f.args]
            o.append('%s __%s_%s(%s) = "\\tjsr\\t-%d(a6)";' % (f.ret, lib.name, f.name, ', '.join(params), f.bias))
            if explicit:
                o.append('#define %s(%s) __%s_%s(%s)' % (name, ', '.join(['__b'] + names), lib.name, f.name,
                                                         ', '.join(['(void *)(__b)'] + ['(%s)' % n for n in names])))
            else:
                o.append('#define %s(%s) __%s_%s(%s)' % (name, ', '.join(names), lib.name, f.name,
                                                         ', '.join(['(void *)(%s)' % lib.basevar] + ['(%s)' % n for n in names])))
            continue
        params = ['%s %s' % (t, n) for t, n, r in f.args]
        if explicit:
            params = ['void *__base'] + params
        o.append('static inline __attribute__((always_inline)) %s %s(%s)\n{' % (f.ret, name, ', '.join(params) or 'void'))
        used = {r for t, n, r in f.args}
        for r in SCRATCH:
            o.append('\tregister unsigned long _%s __asm("%s");' % (r, r))
        for t, n, r in f.args:
            if r not in SCRATCH:
                o.append('\tregister unsigned long _%s __asm("%s") = (unsigned long)(%s);' % (r, r, n))
        # a6 may be GCC's frame pointer (m68k-linux), so it cannot be a
        # register variable: load it inside the asm and restore it.
        o.append('\tvoid *_base = (void *)%s;' % ('__base' if explicit else lib.basevar))
        for t, n, r in f.args:
            if r in SCRATCH:
                o.append('\t_%s = (unsigned long)(%s);' % (r, n))
        outs = ['"%s"(_%s)' % ('+r' if r in used else '=r', r) for r in SCRATCH]
        ins = ['[base] "a"(_base)'] + ['"r"(_%s)' % r for t, n, r in f.args if r not in SCRATCH]
        o.append('\t__asm volatile ("move.l %%%%a6,-(%%%%sp)\\n\\tmove.l %%[base],%%%%a6\\n\\tjsr -%d(%%%%a6)\\n\\tmove.l (%%%%sp)+,%%%%a6"\n\t\t: %s\n\t\t: %s\n\t\t: "cc", "memory");'
                 % (f.bias, ', '.join(outs), ', '.join(ins)))
        if is_void(f.ret):
            o.append('\t(void)_d0;')
        else:
            o.append('\treturn (%s)_d0;' % f.ret)
        o.append('}')
    o.append('#endif')
    open(out, 'w').write('\n'.join(o) + '\n')


def gen_impl(lib, cc, out_src, out_h):
    pfx = lib.opts.get('prefix', lib.name + '_')
    null = '%s_null' % lib.name
    h = ['/* Generated by tools/gen_lvos.py from the LVO table - do not edit. */',
         '#ifndef _RT_GEN_%s_IMPL_H' % lib.name.upper(),
         '#define _RT_GEN_%s_IMPL_H' % lib.name.upper(),
         '/* include amiga_os.h first (types, RTREG) */',
         'extern const ULONG %s_vectors[];' % lib.name,
         '#define %s_NUM_VECTORS %d' % (lib.name.upper(), max(f.bias for f in lib.funcs) // 6)]
    byb = {}
    impls = []
    for f in lib.funcs:
        byb[f.bias] = f
        cfun = f.cname if f.cname else pfx + f.name
        f.cfun = None if cfun == 'null' else cfun
        if f.cfun is None:
            continue
        ret = 'ULONG' if f.ret.endswith('*') or f.ret in ('APTR', 'STRPTR', 'CONST_STRPTR') else f.ret
        params = ', '.join(['RTREG(a6) struct Library *base'] +
                           ['RTREG(%s) %s %s' % (r, t, n) for t, n, r in f.args])
        h.append('%s %s(%s);' % (ret, f.cfun, params))
        impls.append(f)
    h.append('#endif')
    top = max(byb)
    if cc == 'gcc':
        s = ['| Generated by tools/gen_lvos.py from the LVO table - do not edit.',
             '| Trampolines: AmigaOS register arguments -> C stack arguments.',
             '\t.text', '\t.even']
        for f in impls:
            s.append('%s_tr_%s:' % (lib.name, f.name))
            for t, n, r in reversed(f.args):
                s.append('\tmove.l %%%s,-(%%sp)' % r)
            s.append('\tmove.l %a6,-(%sp)')
            s.append('\tjsr %s' % f.cfun)
            s.append('\tlea %d(%%sp),%%sp' % (4 * (len(f.args) + 1)))
            s.append('\tmove.l %d0,%a0')
            s.append('\trts')
        s += ['%s:' % null, '\tmoveq #0,%d0', '\tsub.l %a0,%a0', '\trts',
              '\t.section .rodata', '\t.even', '\t.globl %s_vectors' % lib.name, '%s_vectors:' % lib.name]
        for b in range(6, top + 1, 6):
            f = byb.get(b)
            tgt = '%s_tr_%s' % (lib.name, f.name) if f and f.cfun else null
            s.append('\t.long %s\t| -%d %s' % (tgt, b, f.name if f else '(hole)'))
        s += ['\t.long -1', '\t.section .note.GNU-stack,"",@progbits']
    else:
        s = ['/* Generated by tools/gen_lvos.py from the LVO table - do not edit. */',
             '#include "amiga_os.h"', '#include "%s"' % out_h.split('/')[-1],
             'static ULONG %s(void) { return 0; }' % null,
             'const ULONG %s_vectors[] = {' % lib.name]
        for b in range(6, top + 1, 6):
            f = byb.get(b)
            tgt = f.cfun if f and f.cfun else null
            s.append('\t(ULONG)%s,\t/* -%d %s */' % (tgt, b, f.name if f else '(hole)'))
        s += ['\t(ULONG)-1', '};']
    open(out_src, 'w').write('\n'.join(s) + '\n')
    open(out_h, 'w').write('\n'.join(h) + '\n')


def main():
    a = sys.argv[1:]
    if len(a) < 3:
        sys.exit('usage: gen_lvos.py call|impl gcc|vbcc TABLE LIB OUT... | list TABLE LIB')
    if a[0] == 'list':
        libs = parse(a[1])
        for f in libs[a[2]].funcs:
            print(f.bias, f.name, ','.join(r for t, n, r in f.args))
        return
    mode, cc, table, name = a[:4]
    if cc not in ('gcc', 'vbcc'):
        sys.exit('CC must be gcc or vbcc')
    libs = parse(table)
    if name not in libs:
        sys.exit('library %s not in %s' % (name, table))
    if mode == 'call':
        gen_call(libs[name], cc, a[4])
    elif mode == 'impl':
        gen_impl(libs[name], cc, a[4], a[5])
    else:
        sys.exit('bad mode')


if __name__ == '__main__':
    main()
